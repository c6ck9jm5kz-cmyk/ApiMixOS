import { createFileRoute, redirect } from '@tanstack/react-router'
import z from 'zod'

import { ApiDocs } from '@/features/api-docs'
import { getFreshModuleAccess } from '@/lib/nav-modules'
import { useAuthStore } from '@/stores/auth-store'

const docsSearchSchema = z.object({
  model: z.string().optional().catch(undefined),
})

// The docs center lists exactly the models on the model plaza, so it follows
// the plaza's visibility setting.
export const Route = createFileRoute('/docs/')({
  validateSearch: docsSearchSchema,
  beforeLoad: async ({ location }) => {
    const access = await getFreshModuleAccess('pricing')
    if (!access.enabled) {
      throw redirect({ to: '/' })
    }
    if (access.requireAuth) {
      const { auth } = useAuthStore.getState()
      if (!auth.user) {
        throw redirect({
          to: '/sign-in',
          search: { redirect: location.href },
        })
      }
    }
  },
  component: ApiDocs,
})
